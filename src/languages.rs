pub fn get(id: LangId) -> &'static Language {
    LANGUAGES.iter().find(|l| l.id == id).expect("language registered")
}

pub fn detect(path: &Path) -> LangId {
    let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_default();
    let ext = path.extension().and_then(|e| e.to_str()).unwrap_or_default().to_lowercase();
    LANGUAGES
        .iter()
        .find(|l| l.file_names.contains(&name) || l.extensions.contains(&ext.as_str()))
        .map_or(LangId::Plain, |l| l.id)
}

