mod tests {
    use super::*;

    #[test]
    fn detects() {
        assert_eq!(detect(Path::new("a/b.SQL")), LangId::Sql);
        assert_eq!(detect(Path::new("dbt_project.yml")), LangId::Yaml);
        assert_eq!(detect(Path::new(".zshrc")), LangId::Shell);
        assert_eq!(detect(Path::new("README")), LangId::Plain);
    }
}
