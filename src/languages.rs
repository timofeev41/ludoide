//! Language registry. Adding a language = adding one entry to [`LANGUAGES`].

use std::path::Path;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum LangId {
    Sql,
    Python,
    Yaml,
    Shell,
    Markdown,
    Json,
    Toml,
    Plain,
}

/// What the editor does when "Run" is pressed for a language.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Runner {
    /// Execute against the active database connection.
    Database,
    /// Execute with the selected Python interpreter in a terminal.
    Python,
    /// Execute with the configured shell in a terminal.
    Shell,
    None,
}

pub struct Language {
    pub id: LangId,
    pub name: &'static str,
    pub extensions: &'static [&'static str],
    pub file_names: &'static [&'static str],
    pub line_comment: Option<&'static str>,
    pub keywords: &'static [&'static str],
    pub builtins: &'static [&'static str],
    pub runner: Runner,
    pub previewable: bool,
}

